// Writes src/lib/html2canvasSource.ts: html2canvas's browser build as a string, so the
// photo export can run it inside a WebView. Run after updating html2canvas: npm run gen:html2canvas
const fs = require("fs"), path = require("path");
const src = fs.readFileSync(require.resolve("html2canvas/dist/html2canvas.min.js"), "utf8");
const out = "// Generated by scripts/gen-html2canvas.js — do not edit.\n/* eslint-disable */\nexport const HTML2CANVAS_JS = " + JSON.stringify(src) + ";\n";
fs.writeFileSync(path.join(__dirname, "../src/lib/html2canvasSource.ts"), out);
